#!/usr/bin/env python3
"""Generate numbered Android vectors from pinned Material Symbols SVGs (Python 3.11+)."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parent
DRAWABLES = ROOT.parent.parent / "app/src/main/res/drawable"
PACKAGE = "@material-symbols/svg-400@0.45.5"
SOURCE_BASE = f"https://unpkg.com/{PACKAGE}/rounded/"
SVG_NAMESPACE = "{http://www.w3.org/2000/svg}"


def vector(source: Path, expected_sha256: str) -> str:
    data = source.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected_sha256:
        raise ValueError(f"Source hash mismatch: {source.name}")
    svg = ET.fromstring(data)
    if (
        svg.tag != SVG_NAMESPACE + "svg"
        or svg.attrib != {"width": "48", "height": "48", "viewBox": "0 -960 960 960"}
        or len(svg) != 1
    ):
        raise ValueError(f"Unsupported SVG root: {source.name}")
    path = svg[0]
    if path.tag != SVG_NAMESPACE + "path" or set(path.attrib) != {"d"} or len(path) or not path.get("d"):
        raise ValueError(f"Expected one path without transforms or styling: {source.name}")
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/custom-icons/generate.py; do not edit. -->
<!-- Source: {PACKAGE} rounded/{source.name}; Apache-2.0. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group
        android:translateY="960">
        <path
            android:fillColor="#FF000000"
            android:pathData={quoteattr(path.attrib["d"])} />
    </group>
</vector>
'''


def main() -> int:
    if sys.version_info < (3, 11):
        raise SystemExit("Python 3.11+ required; use the uv command in README.md")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report stale vectors without changing files")
    args = parser.parse_args()
    manifest = json.loads((ROOT / "sources.json").read_text(encoding="utf-8"))
    if manifest["package"] != PACKAGE or manifest["source_base"] != SOURCE_BASE or manifest["license"] != "Apache-2.0":
        raise ValueError("Unexpected Material Symbols provenance")
    sources = manifest["sha256"]
    expected_names = {f"counter_{number}{suffix}.svg" for number in range(10) for suffix in ("", "-fill")}
    if set(sources) != expected_names or {path.name for path in (ROOT / "sources").iterdir()} != expected_names:
        raise ValueError("Expected exactly counter_0 through counter_9 with filled and outline sources")
    generated = {}
    for number in range(10):
        for style, suffix in (("filled", "-fill"), ("outline", "")):
            source = ROOT / "sources" / f"counter_{number}{suffix}.svg"
            generated[DRAWABLES / f"ic_{style}_custom_{number}.xml"] = vector(source, sources[source.name])
    stale = []
    for destination, content in generated.items():
        if args.check:
            if not destination.is_file() or destination.read_text(encoding="utf-8") != content:
                stale.append(destination.name)
        else:
            destination.write_text(content, encoding="utf-8")
    if stale:
        print("Stale generated vectors: " + ", ".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Generated'} {len(generated)} numbered vectors from {PACKAGE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
